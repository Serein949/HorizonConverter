    private static bool[] MakeFlags(params int[] indices)
    {
        var flags = new bool[16];
        foreach (int i in indices) flags[i] = true;
        return flags;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int Trit(int j, int x) => Trits[(j << 8) + x];

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int Quint(int j, int x) => Quints[(j * 128) + x];

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static int ReverseByte(int c, int bits) => BitReverse[c] >> (8 - bits);
